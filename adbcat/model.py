"""Log entry parsing and storage."""

from __future__ import annotations

import re
import time
from datetime import datetime

LEVEL_CHARS = "VDIWEF"
LEVEL_NAMES = ("VERBOSE", "DEBUG", "INFO", "WARN", "ERROR", "ASSERT")
LEVEL_ALIASES = {
    "V": 0, "VERBOSE": 0,
    "D": 1, "DEBUG": 1,
    "I": 2, "INFO": 2,
    "W": 3, "WARN": 3, "WARNING": 3,
    "E": 4, "ERROR": 4,
    "F": 5, "A": 5, "ASSERT": 5, "FATAL": 5,
}

# Matches `threadtime` output, optionally with `-v year` and `-v uid`.
LINE_RE = re.compile(
    r"^(?:(?P<year>\d{4})-)?(?P<date>\d\d-\d\d)\s+(?P<time>\d\d:\d\d:\d\d\.\d+)\s+"
    r"(?:(?P<uid>\S+)\s+)?(?P<pid>\d+)\s+(?P<tid>\d+)\s+(?P<level>[VDIWEFAS])\s+"
    r"(?P<tag>.*?)\s*:(?: |$)(?P<msg>.*)$"
)

KIND_LOG = 0
KIND_MARKER = 1  # synthetic line generated by adbcat (process start/end, reconnects)
KIND_RAW = 2  # a line we could not parse

_CTRL = {i: None for i in range(32) if i != 9}
_CTRL[127] = None


_NEEDS_CLEAN = re.compile(r"[\x00-\x1f\x7f]")


def sanitize(text: str) -> str:
    if _NEEDS_CLEAN.search(text) is None:
        return text
    return text.expandtabs(4).translate(_CTRL)


class Entry:
    __slots__ = (
        "seq", "ts", "uid", "pid", "tid", "level", "tag", "msg", "raw",
        "pkg", "proc", "kind", "bookmark", "_epoch",
    )

    def __init__(self, ts="", uid="", pid=0, tid=0, level=2, tag="", msg="", raw="",
                 kind=KIND_LOG):
        self.seq = -1
        self.ts = ts
        self.uid = uid
        self.pid = pid
        self.tid = tid
        self.level = level
        self.tag = tag
        self.msg = msg
        self.raw = raw
        self.pkg: str | None = None
        self.proc: str | None = None
        self.kind = kind
        self.bookmark = False
        self._epoch: float | None = None

    @property
    def level_char(self) -> str:
        return LEVEL_CHARS[self.level]

    @property
    def epoch(self) -> float:
        """Timestamp as seconds since the epoch (host local time)."""
        if self._epoch is None:
            ts = self.ts
            try:
                if len(ts) > 4 and ts[4] == "-":
                    dt = datetime.strptime(ts[:23], "%Y-%m-%d %H:%M:%S.%f")
                else:
                    dt = datetime.strptime(
                        f"{datetime.now().year}-{ts[:18]}", "%Y-%m-%d %H:%M:%S.%f"
                    )
                self._epoch = dt.timestamp()
            except ValueError:
                self._epoch = time.time()
        return self._epoch

    @property
    def time_str(self) -> str:
        """HH:MM:SS.mmm"""
        return self.ts[-12:] if self.ts else ""

    @property
    def date_str(self) -> str:
        """MM-DD"""
        if len(self.ts) > 4 and self.ts[4] == "-":
            return self.ts[5:10]
        return self.ts[:5]


def parse_line(line: str) -> Entry | None:
    """Parse one logcat line. Returns None for lines that should be dropped."""
    line = line.rstrip("\r\n")
    if not line or line.startswith("--------- "):
        return None
    e = _fast_parse(line)
    if e is not None:
        return e
    m = LINE_RE.match(line)
    if m is None:
        return Entry(msg=sanitize(line), raw=line, tag="", level=2, kind=KIND_RAW)
    year = m.group("year")
    ts = f"{year}-{m.group('date')} {m.group('time')}" if year else f"{m.group('date')} {m.group('time')}"
    lvl = m.group("level")
    return Entry(
        ts=ts,
        uid=m.group("uid") or "",
        pid=int(m.group("pid")),
        tid=int(m.group("tid")),
        level=LEVEL_ALIASES.get(lvl, 0) if lvl != "S" else 0,
        tag=sanitize(m.group("tag")),
        msg=sanitize(m.group("msg")),
        raw=line,
    )


_LEVEL_INDEX = {"V": 0, "D": 1, "I": 2, "W": 3, "E": 4, "F": 5, "A": 5, "S": 0}


def _fast_parse(line: str) -> Entry | None:
    """str.split based parser for the common case; None means "use the regex"."""
    parts = line.split(None, 5)
    if len(parts) < 6:
        return None
    date, tm, a, b, c, rest = parts
    if len(tm) < 12 or tm[2] != ":" or not (len(date) == 10 and date[4] == "-" or len(date) == 5):
        return None
    if len(c) == 1 and c in _LEVEL_INDEX and a.isdigit() and b.isdigit():
        uid, pid, tid, level = "", a, b, c
    elif len(rest) > 2 and rest[1] == " " and rest[0] in _LEVEL_INDEX and b.isdigit() and c.isdigit():
        uid, pid, tid, level = a, b, c, rest[0]
        rest = rest[2:].lstrip(" ")
    else:
        return None
    i = rest.find(": ")
    if i < 0:
        if not rest.endswith(":"):
            return None
        i = len(rest) - 1
    tag = rest[:i].rstrip(" ")
    msg = rest[i + 2:]
    if "\t" in tag or "\t" in msg or _NEEDS_CLEAN.search(tag) or _NEEDS_CLEAN.search(msg):
        tag, msg = sanitize(tag), sanitize(msg)
    return Entry(ts=f"{date} {tm}", uid=uid, pid=int(pid), tid=int(tid),
                 level=_LEVEL_INDEX[level], tag=tag, msg=msg, raw=line)


def now_ts() -> str:
    t = time.time()
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(t)) + f".{int(t % 1 * 1000):03d}"


def make_marker(text: str, pid: int = 0, pkg: str | None = None, level: int = 2) -> Entry:
    ts = now_ts()
    e = Entry(ts=ts, pid=pid, tid=pid, level=level, tag="adbcat", msg=text,
              raw=f"{ts}     0 {pid:5d} {pid:5d} {LEVEL_CHARS[level]} adbcat  : {text}",
              kind=KIND_MARKER)
    e.pkg = pkg
    e.proc = pkg
    return e


class LogStore:
    """Bounded list of entries addressed by a monotonically increasing sequence number."""

    def __init__(self, max_lines: int = 200_000):
        self.max_lines = max_lines
        self.entries: list[Entry] = []
        self.base = 0
        self.next_seq = 0
        self.dropped = 0

    def __len__(self) -> int:
        return len(self.entries)

    def append(self, entry: Entry) -> None:
        entry.seq = self.next_seq
        self.next_seq += 1
        self.entries.append(entry)

    def get(self, seq: int) -> Entry | None:
        i = seq - self.base
        if 0 <= i < len(self.entries):
            return self.entries[i]
        return None

    def trim(self) -> bool:
        """Drop the oldest entries once we go 10% over the limit. Returns True if trimmed."""
        if len(self.entries) <= self.max_lines * 1.1:
            return False
        drop = len(self.entries) - self.max_lines
        del self.entries[:drop]
        self.base += drop
        self.dropped += drop
        return True

    def clear(self) -> None:
        self.entries = []
        self.base = self.next_seq
